require('dotenv').config();
const express=require('express');
const cors=require('cors');
const helmet=require('helmet');
const cookieParser=require('cookie-parser');
const rateLimit=require('express-rate-limit');
const {notFound,errorHandler}=require('./middleware/errors');
const authRoutes=require('./routes/authRoutes');
const farmRoutes=require('./routes/farmRoutes');
const cropRoutes=require('./routes/cropRoutes');
const marketRoutes=require('./routes/marketRoutes');
const communityRoutes=require('./routes/communityRoutes');
const soilRoutes=require('./routes/soilRoutes');
const notificationRoutes=require('./routes/notificationRoutes');
const adminRoutes=require('./routes/adminRoutes');
const supportRoutes=require('./routes/supportRoutes');
const weatherController=require('./controllers/weatherController');
const asyncHandler=require('./utils/asyncHandler');
const {protect}=require('./middleware/auth');
const app=express();
app.disable('x-powered-by');
app.use(helmet({crossOriginResourcePolicy:{policy:'cross-origin'}}));
app.use(cors({origin:process.env.CLIENT_URL||'http://localhost:5173',credentials:true}));
app.use(express.json({limit:'1mb'}));
app.use(express.urlencoded({extended:false,limit:'1mb'}));
app.use(cookieParser());
app.use('/api/v1/auth',rateLimit({windowMs:15*60*1000,limit:100,standardHeaders:true,legacyHeaders:false}),authRoutes);
app.get('/api/v1/health',asyncHandler(async(req,res)=>{const mongoose=require('mongoose');const dbState=mongoose.connection.readyState;res.status(dbState===1?200:503).json({status:dbState===1?'ok':'degraded',service:'agritech-api',database:dbState===1?'connected':'disconnected',timestamp:new Date().toISOString()});}));
app.use('/api/v1/farms',farmRoutes);
app.use('/api/v1/crops',cropRoutes);
app.use('/api/v1',marketRoutes);
app.use('/api/v1/community',communityRoutes);
app.use('/api/v1/soil-records',soilRoutes);
app.use('/api/v1/notifications',notificationRoutes);
app.use('/api/v1/admin',adminRoutes);
app.use('/api/v1/support',supportRoutes);
app.get('/api/v1/weather',rateLimit({windowMs:60*1000,limit:30,standardHeaders:true,legacyHeaders:false}),weatherController.current);
app.get('/api/v1/dashboard/summary',protect,asyncHandler(async(req,res)=>{const Farm=require('./models/Farm');const Crop=require('./models/Crop');const Order=require('./models/Order');const Booking=require('./models/Booking');const [farms,crops,orders,bookings]=await Promise.all([Farm.countDocuments({owner:req.user._id}),Crop.countDocuments({owner:req.user._id}),Order.countDocuments({customer:req.user._id}),Booking.countDocuments({customer:req.user._id})]);res.json({summary:{farms,crops,orders,bookings}});}));
app.use(notFound);
app.use(errorHandler);
module.exports=app;
